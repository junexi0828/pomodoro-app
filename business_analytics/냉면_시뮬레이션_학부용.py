"""
냉면 수량 결정 시뮬레이션 (학부용)

문제 설정:
- 온도와 날씨에 따라 냉면 수요가 변함
- 온도: 0°C ~ 30°C (균등분포)
- 날씨: 맑음 80%, 흐림 20%
- 수요공식: 맑은 날 μd = 100 + 3t, 흐린 날 μd = 30 + 4t
- 표준편차: 맑은 날 σd = 0.5μd, 흐린 날 σd = 0.6μd
"""

import numpy as np
import matplotlib.pyplot as plt

# ===============================================
# 1단계: 기본 설정
# ===============================================

print("=" * 50)
print("냉면 수량 결정 시뮬레이션")
print("=" * 50)

# 시뮬레이션 횟수 (많을수록 정확하지만 시간이 오래 걸림)
n = 10000
print(f"시뮬레이션 횟수: {n:,}회")

# 비용과 가격 설정
판매가격 = 8000  # 냉면 한 그릇 판매가격
생산비용 = 2000  # 냉면 한 그릇 생산비용
폐기비용 = 0     # 남은 냉면 폐기비용 (여기서는 0으로 가정)

품절비용 = 판매가격 - 생산비용  # 팔지 못해서 잃는 이익
재고비용 = 생산비용 - 폐기비용  # 남아서 손해보는 비용

print(f"\n[비용 정보]")
print(f"판매가격: {판매가격:,}원")
print(f"생산비용: {생산비용:,}원")
print(f"품절비용: {품절비용:,}원 (기회손실)")
print(f"재고비용: {재고비용:,}원 (과잉재고)")

# ===============================================
# 2단계: 수요 데이터 생성
# ===============================================

print(f"\n[수요 데이터 생성]")

# 온도 생성 (0°C ~ 30°C, 균등분포)
온도 = np.random.uniform(0, 30, n)
print(f"온도 범위: 0°C ~ 30°C (균등분포)")

# 날씨 생성 (맑음=0이 80%, 흐림=1이 20%)
날씨 = np.random.binomial(1, 0.2, n)  # 0.2 확률로 흐림(1), 0.8 확률로 맑음(0)
print(f"날씨 확률: 맑음(0) 80%, 흐림(1) 20%")

# 실제 수요 계산
수요 = np.zeros(n)

for i in range(n):
    if 날씨[i] == 0:  # 맑은 날
        평균수요 = 100 + 3 * 온도[i]
        표준편차 = 0.5 * 평균수요
    else:  # 흐린 날
        평균수요 = 30 + 4 * 온도[i]
        표준편차 = 0.6 * 평균수요

    # 정규분포에서 수요 생성
    실제수요 = np.random.normal(평균수요, 표준편차)

    # 수요는 0보다 작을 수 없음
    if 실제수요 < 0:
        실제수요 = 0

    수요[i] = 실제수요

# 수요 분석
맑은날_수요 = 수요[날씨 == 0]
흐린날_수요 = 수요[날씨 == 1]

print(f"\n[수요 분석 결과]")
print(f"전체 평균 수요: {np.mean(수요):.1f}그릇")
print(f"맑은 날 평균 수요: {np.mean(맑은날_수요):.1f}그릇 (샘플: {len(맑은날_수요):,}개)")
print(f"흐린 날 평균 수요: {np.mean(흐린날_수요):.1f}그릇 (샘플: {len(흐린날_수요):,}개)")

# ===============================================
# 3단계: 생산량 결정 방법 1 - 평균 수요로 생산
# ===============================================

print(f"\n[방법 1: 평균 수요로 생산]")

총이익1 = 0
총생산량1 = 0

for i in range(n):
    # 각 상황에서 평균 수요만큼 생산
    if 날씨[i] == 0:  # 맑은 날
        생산량 = 100 + 3 * 온도[i]
    else:  # 흐린 날
        생산량 = 30 + 4 * 온도[i]

    실제수요 = 수요[i]

    # 이익 계산
    이익 = -생산비용 * 생산량  # 일단 생산비용 지출

    if 실제수요 <= 생산량:  # 수요가 생산량보다 적거나 같은 경우
        이익 += 판매가격 * 실제수요  # 실제 판매된 만큼 수익
        # 남은 것은 폐기 (폐기비용 = 0이므로 추가 손실 없음)
    else:  # 수요가 생산량보다 많은 경우 (품절)
        이익 += 판매가격 * 생산량  # 생산한 만큼만 판매

    총이익1 += 이익
    총생산량1 += 생산량

평균생산량1 = 총생산량1 / n
평균이익1 = 총이익1 / n

print(f"평균 생산량: {평균생산량1:.1f}그릇")
print(f"평균 이익: {평균이익1:.0f}원")

# ===============================================
# 4단계: 생산량 결정 방법 2 - 조금 더 많이 생산
# ===============================================

print(f"\n[방법 2: 평균보다 20% 더 생산]")

총이익2 = 0
총생산량2 = 0

for i in range(n):
    # 평균 수요보다 20% 더 생산
    if 날씨[i] == 0:  # 맑은 날
        생산량 = (100 + 3 * 온도[i]) * 1.2
    else:  # 흐린 날
        생산량 = (30 + 4 * 온도[i]) * 1.2

    실제수요 = 수요[i]

    # 이익 계산 (방법 1과 동일)
    이익 = -생산비용 * 생산량

    if 실제수요 <= 생산량:
        이익 += 판매가격 * 실제수요
    else:
        이익 += 판매가격 * 생산량

    총이익2 += 이익
    총생산량2 += 생산량

평균생산량2 = 총생산량2 / n
평균이익2 = 총이익2 / n

print(f"평균 생산량: {평균생산량2:.1f}그릇")
print(f"평균 이익: {평균이익2:.0f}원")

# ===============================================
# 5단계: 생산량 결정 방법 3 - 조금 덜 생산
# ===============================================

print(f"\n[방법 3: 평균보다 20% 덜 생산]")

총이익3 = 0
총생산량3 = 0

for i in range(n):
    # 평균 수요보다 20% 덜 생산
    if 날씨[i] == 0:  # 맑은 날
        생산량 = (100 + 3 * 온도[i]) * 0.8
    else:  # 흐린 날
        생산량 = (30 + 4 * 온도[i]) * 0.8

    실제수요 = 수요[i]

    # 이익 계산
    이익 = -생산비용 * 생산량

    if 실제수요 <= 생산량:
        이익 += 판매가격 * 실제수요
    else:
        이익 += 판매가격 * 생산량

    총이익3 += 이익
    총생산량3 += 생산량

평균생산량3 = 총생산량3 / n
평균이익3 = 총이익3 / n

print(f"평균 생산량: {평균생산량3:.1f}그릇")
print(f"평균 이익: {평균이익3:.0f}원")

# ===============================================
# 6단계: 결과 비교 및 분석
# ===============================================

print(f"\n" + "=" * 50)
print("결과 비교")
print("=" * 50)

print(f"방법 1 (평균 수요): 생산량 {평균생산량1:.1f}, 이익 {평균이익1:.0f}원")
print(f"방법 2 (+20% 생산): 생산량 {평균생산량2:.1f}, 이익 {평균이익2:.0f}원")
print(f"방법 3 (-20% 생산): 생산량 {평균생산량3:.1f}, 이익 {평균이익3:.0f}원")

# 최고 이익을 내는 방법 찾기
이익들 = [평균이익1, 평균이익2, 평균이익3]
방법들 = ["평균 수요", "+20% 생산", "-20% 생산"]
최고_방법 = 방법들[np.argmax(이익들)]
최고_이익 = max(이익들)

print(f"\n최고 이익 방법: {최고_방법} ({최고_이익:.0f}원)")

# ===============================================
# 7단계: 온도별 수요 패턴 분석
# ===============================================

print(f"\n" + "=" * 50)
print("온도별 수요 패턴 분석")
print("=" * 50)

온도구간 = [(0, 10), (10, 20), (20, 30)]

for 최소온도, 최대온도 in 온도구간:
    # 해당 온도 구간의 데이터만 선택
    온도범위 = (온도 >= 최소온도) & (온도 < 최대온도)
    구간수요 = 수요[온도범위]
    구간날씨 = 날씨[온도범위]

    if len(구간수요) > 0:
        맑은날_구간수요 = 구간수요[구간날씨 == 0]
        흐린날_구간수요 = 구간수요[구간날씨 == 1]

        print(f"\n온도 {최소온도}°C ~ {최대온도}°C:")
        print(f"  전체 평균 수요: {np.mean(구간수요):.1f}그릇")
        if len(맑은날_구간수요) > 0:
            print(f"  맑은 날 평균: {np.mean(맑은날_구간수요):.1f}그릇")
        if len(흐린날_구간수요) > 0:
            print(f"  흐린 날 평균: {np.mean(흐린날_구간수요):.1f}그릇")

# ===============================================
# 8단계: 간단한 수요 예측 공식 제시
# ===============================================

print(f"\n" + "=" * 50)
print("수요 예측 공식 (참고용)")
print("=" * 50)

print("맑은 날 (확률 80%):")
print("  평균 수요 = 100 + 3 × 온도")
print("  예) 온도 20°C → 평균 수요 = 100 + 3×20 = 160그릇")

print("\n흐린 날 (확률 20%):")
print("  평균 수요 = 30 + 4 × 온도")
print("  예) 온도 20°C → 평균 수요 = 30 + 4×20 = 110그릇")

print("\n종합 예상 수요 (온도 20°C 기준):")
예상수요_20도 = 0.8 * (100 + 3*20) + 0.2 * (30 + 4*20)
print(f"  0.8 × 160 + 0.2 × 110 = {예상수요_20도:.1f}그릇")

print(f"\n프로그램 실행 완료!")
print(f"시뮬레이션 데이터: {n:,}개 사용")